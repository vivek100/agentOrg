/**
 * Writes frontend/.env.local from linked .insforge/project.json + `npx @insforge/cli secrets get`.
 * Run from repo root: node scripts/write-insforge-env.mjs
 * Does not print secret values.
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const projectPath = path.join(root, ".insforge", "project.json");

if (!fs.existsSync(projectPath)) {
  console.error("Missing .insforge/project.json — run: npx @insforge/cli link --project-id <id>");
  process.exit(1);
}

const proj = JSON.parse(fs.readFileSync(projectPath, "utf8"));
const publicUrl = String(proj.oss_host ?? "").replace(/\/$/, "");
if (!publicUrl) {
  console.error("Missing oss_host in .insforge/project.json");
  process.exit(1);
}

/** CLI prints `ANON_KEY = <jwt>` — keep only the value. */
function parseSecretLine(raw) {
  const line = (raw.trim().match(/[^\r\n]+/) ?? [""])[0];
  const m = line.match(/^[A-Z0-9_]+\s*=\s*(.+)$/);
  return (m ? m[1] : line).trim();
}

function getSecret(name) {
  const out = execSync(`npx @insforge/cli secrets get ${name}`, {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  });
  return parseSecretLine(out);
}

const anon = getSecret("ANON_KEY");
const api = getSecret("API_KEY");
if (!anon || !api) {
  console.error("Empty ANON_KEY or API_KEY from CLI.");
  process.exit(1);
}

const content = `# InsForge — generated by scripts/write-insforge-env.mjs (do not commit)
INSFORGE_URL=${publicUrl}
INSFORGE_SERVICE_KEY=${api}
NEXT_PUBLIC_INSFORGE_URL=${publicUrl}
NEXT_PUBLIC_INSFORGE_ANON_KEY=${anon}

# Mastra / OpenAI (optional until wired)
# OPENAI_API_KEY=

# Set to 1 only to use in-browser timer mock instead of POST /api/orgs/generate
# NEXT_PUBLIC_AGENTORG_OFFLINE_MOCK=
`;

const out = path.join(root, "frontend", ".env.local");
fs.writeFileSync(out, content, "utf8");
console.log("OK: wrote", path.relative(root, out), "for", publicUrl);
